/**
 * 这个解答效率高
 * 但是基于这里是标准的子集，使用的是子集的特点
 * 
 */
function subsets(nums) {
    let res=[[]]
    for(let i=0;i<nums.length;i++){
        const size = res.length;   
        for(let j=0;j<size;j++){
            res.push([...res[j],nums[i]])
        }
    }
    return res
};


